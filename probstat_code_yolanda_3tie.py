EX, EY = (x * pX).sum(), (y * pY).sum()
EXY = sum(i * j * joint.loc[i, j] for i in x for j in y)
cov = EXY - EX * EY
varX = (x**2 * pX).sum() - EX**2
varY = (y**2 * pY).sum() - EY**2
