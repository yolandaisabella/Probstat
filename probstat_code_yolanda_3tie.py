"""**Base Rate Fallacy: Deteksi Malware dan Pembaruan Bayes Berurutan**"""

import numpy as np
import matplotlib.pyplot as plt

sens, fpr = 0.99, 0.05

def posterior(prior, sens=sens, fpr=fpr):
    """P(malware | hasil positif) dengan prior tertentu"""
    return sens * prior / (sens * prior + fpr * (1 - prior))

prior = 0.01
post1 = posterior(prior)
post2 = posterior(post1)           # posterior pertama dipakai sebagai prior kedua
post3 = posterior(post2)
print(f"Prior (prevalensi)          : {prior:.4f}")
print(f"Setelah 1x positif          : {post1:.4f}")
print(f"Setelah 2x positif berturut : {post2:.4f}")
print(f"Setelah 3x positif berturut : {post3:.4f}")

# Pengaruh prevalensi
for pr in [0.001, 0.01, 0.05, 0.10, 0.30, 0.50]:
    print(f"prevalensi {pr:6.3f} -> P(malware | +) = {posterior(pr):.4f}")

# Verifikasi simulasi untuk 1x positif
rng = np.random.default_rng(11)
N = 3_000_000
malware = rng.random(N) < prior
positif = np.where(malware, rng.random(N) < sens, rng.random(N) < fpr)
print(f"\nSimulasi P(malware | +) = {malware[positif].mean():.4f}")

# Grafik
pr = np.linspace(0.0005, 0.6, 400)
