"""**Probabilitas Total dan Bayes dengan Banyak Hipotesis: Load Balancer**"""

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.DataFrame({"prior": [0.50, 0.30, 0.20],
                   "p_error": [0.01, 0.02, 0.05]},
                  index=["Server A", "Server B", "Server C"])

df["prior*error"] = df["prior"] * df["p_error"]
P_error = df["prior*error"].sum()                 # probabilitas total
df["posterior"] = df["prior*error"] / P_error     # teorema Bayes
print(df.round(4))
print(f"\nP(Error) = {P_error:.4f}")
print("Jumlah posterior =", df["posterior"].sum().round(4))

# Verifikasi simulasi
rng = np.random.default_rng(3)
N = 2_000_000
server = rng.choice(3, N, p=df["prior"])
error = rng.random(N) < df["p_error"].values[server]
print(f"\nSimulasi P(Error) = {error.mean():.4f}")
print("Simulasi P(Server | Error) =", np.round(np.bincount(server[error]) / error.sum(), 4))

# Visualisasi prior vs posterior
x = np.arange(3)
plt.figure(figsize=(6.5, 3.6))
plt.bar(x - 0.2, df["prior"], 0.4, label="Prior P(S)")
