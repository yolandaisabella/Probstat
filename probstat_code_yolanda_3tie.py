import seaborn as sns
import matplotlib.pyplot as plt

# Baris = X (error), kolom = Y (warning)
joint = pd.DataFrame([[0.20, 0.10, 0.05],
                      [0.10, 0.25, 0.10],
                      [0.02, 0.08, 0.10]],
                     index=pd.Index([0, 1, 2], name="X (error)"),
                     columns=pd.Index([0, 1, 2], name="Y (warning)"))
