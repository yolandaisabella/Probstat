"""**Kombinasi Kejadian: Gabungan, Irisan, Komplemen, dan Inklusi-Eksklusi**"""

from itertools import combinations
import matplotlib.pyplot as plt
from matplotlib.patches import Circle

U = set(range(100))
A, B, C = set(range(0, 50)), set(range(30, 70)), set(range(60, 90))
P = lambda s: len(s) / len(U)

print("P(A), P(B), P(C)  :", P(A), P(B), P(C))
print("P(A∩B)            :", P(A & B))
print("P(A∩C)            :", P(A & C))
print("P(B∩C)            :", P(B & C))
print("P(A∩B∩C)          :", P(A & B & C))

# Cara 1: langsung dengan operasi himpunan
p_union_langsung = P(A | B | C)

# Cara 2: rumus inklusi-eksklusi
S = [A, B, C]
p_ie = 0
for k in range(1, 4):
    tanda = (-1) ** (k + 1)
    for kombinasi in combinations(S, k):
        irisan = set.intersection(*kombinasi)
        p_ie += tanda * P(irisan)

print(f"\nP(A∪B∪C) langsung        = {p_union_langsung:.2f}")
print(f"P(A∪B∪C) inklusi-eksklusi = {p_ie:.2f}")
print(f"P(tidak memakai fitur)    = {P(U - (A | B | C)):.2f}  (= 1 - P(A∪B∪C) = {1 - p_ie:.2f})")
print(f"P(hanya Chat)             = {P(A - B - C):.2f}")
print(f"P(Chat atau Video, bukan Pembayaran) = {P((A | B) - C):.2f}")

# Diagram Venn sederhana
fig, ax = plt.subplots(figsize=(5.5, 3.6))
